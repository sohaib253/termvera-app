# ---------------------------------------------------------------------------
# Risk rules
# ---------------------------------------------------------------------------

@dataclass(frozen=True)
class Rule:
    id: str
    risk_type: str
    triggers: tuple[str, ...]
    description: str
    action: str
    severity: str = "medium"
    requires: tuple[str, ...] = ()
    scope: str = "sentence"
    unless: tuple[str, ...] = ()
    bands: tuple[str, str, tuple[tuple[float, str], ...], str | None] | None = None
    escalate: tuple[tuple[str, str], ...] = ()
    mitigate: tuple[tuple[str, str], ...] = ()
    context: tuple[tuple[str, str], ...] = ()
    effect: str = ""
    affected_party: str = "contractor"
    subcategories: tuple[str, ...] = field(default_factory=tuple)


def R(id: str, risk_type: str, triggers: tuple[str, ...], description: str, action: str, **kw) -> Rule:
    for key in ("requires", "unless"):
        if key in kw:
            kw[key] = _x(kw[key])
    for key in ("escalate", "mitigate", "context"):
        if key in kw:
            kw[key] = tuple((_x((p,))[0], v) for p, v in kw[key])
    return Rule(id=id, risk_type=risk_type, triggers=_x(triggers), description=description, action=action, **kw)


