"""Contract knowledge base: how to classify a clause and what risk it carries.

Written from the contractor / supplier / service provider side of the
table, which is who this product serves: the question every rule answers
is "what does this clause cost us, and when?".

Party names vary by contract family (Company / Employer / Owner / Buyer /
Customer on one side; Contractor / Supplier / Vendor / Consultant /
Service Provider on the other), so patterns use {K} for the client side
and {C} for the contractor side, expanded at load time.

Adding coverage means adding a rule here. A rule has:
  triggers   - any of these in a sentence makes that sentence the evidence
  requires   - all of these must also appear (in the sentence, or clause
               when scope="clause")
  unless     - any of these anywhere in the clause suppresses the rule
               (a mitigant the drafting already provides)
  severity   - base severity
  bands      - numeric escalation from the figure in the evidence sentence
  escalate / mitigate - cues in the clause that move severity up or down
  context    - cues in *related* clauses that aggravate this one
"""

from dataclasses import dataclass, field

K = r"(?:company|client|employer|owner|purchaser|buyer|customer|principal|authority|operator|contracting entity)"
C = r"(?:contractor|supplier|vendor|consultant|service provider|seller|provider|subcontractor|manufacturer)"


def _x(patterns: tuple[str, ...]) -> tuple[str, ...]:
    return tuple(p.replace("{K}", K).replace("{C}", C) for p in patterns)


